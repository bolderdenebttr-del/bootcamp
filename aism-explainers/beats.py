REG = {'paper': 'Paper', 'ink': 'Ink', 'khadag': 'Khadag'}


def fx_for(cues, a, b):
    out = [f"{c['type']} {c['t'] - a:+.2f}" for c in cues if a - 1e-3 <= c['t'] < b - 1e-3]
    return ', '.join(out) or 'none'


def main():
    md = ['# AISM motion explainers: beat sheets', '',
          'Generated by `beats.py` from the rendered timelines. Times are seconds on the final video. '
          'Each row is one shot; caption phrases are listed as lead / **punch** / tail with the accent word in *italics*. '
          'Effects are offsets from the shot start.', '']
    for v, (fname, title, desc) in VIDEOS.items():
        b = json.load(open(os.path.join(ROOT, 'build', v, 'beats.json')))
        shots = b['shots']
        assert len(shots) == len(desc), (v, len(shots), len(desc))
        share = {}
        for s in shots:
            share[s['reg']] = share.get(s['reg'], 0) + s['dur']
        md += [f'## {v} · {title}', '', f'File: `out/{fname}` · {b["end"]:.2f} s · {len(shots)} shots · '
               + ', '.join(f'{REG[k]} {100 * share.get(k, 0) / b["end"]:.0f}%' for k in ('paper', 'ink', 'khadag')), '',
               '| Time | Register | Code | Scene | Captions (lead / **punch** / tail) | Accent | Effects |',
               '|---|---|---|---|---|---|---|']
        for s, (code, d) in zip(shots, desc):
            caps = '<br>'.join(f"{c['lead']} / **{c['punch']}**" + (f" / {c['tail']}" if c['tail'] else '') for c in s['caps']) or '(end card)'
            acc = ', '.join(f"*{a}*" for c in s['caps'] for a in c['accent']) or 'none'
            reg = REG[s['reg']] + (' (ribbon)' if s['ribbon'] else '')
            md.append(f"| {s['at']:.2f}–{s['at'] + s['dur']:.2f} | {reg} | {code} | {d} | {caps} | {acc} | {fx_for(b['cues'], s['at'], s['at'] + s['dur'])} |")
        md.append('')
    open(os.path.join(ROOT, 'BEATS.md'), 'w').write('\n'.join(md))
    print('wrote BEATS.md')


if __name__ == '__main__':
    main()
