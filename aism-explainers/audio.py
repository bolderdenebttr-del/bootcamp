"""AISM explainer audio.

  python3 audio.py align <video>   force-align the corrected script, trim pauses, process dialogue
                                   -> videos/<video>_words.js, build/<video>/voice.wav
  python3 audio.py mix <video>     bed + effects from build/<video>/cues.json, loudness to -14 LUFS
                                   -> build/<video>/mix.wav
"""
import json, os, subprocess, sys
import numpy as np
from scipy import signal
import pyloudnorm as pyln
from pauses import load, speech_regions, SR

ROOT = os.path.dirname(os.path.abspath(__file__))
PAUSE = 0.0          # extra gap between padded regions (padding already leaves ~0.12 s)
LONG_PAUSE = 0.45    # kept once, before the turn to AISM


def wav_write(path, x, sr=SR):
    x = np.asarray(x, dtype=np.float32)
    ch = 1 if x.ndim == 1 else x.shape[1]
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'f32le', '-ar', str(sr), '-ac', str(ch), '-i', '-',
                    '-c:a', 'pcm_f32le', path], input=x.tobytes(), check=True)


def wav_read(path, ch=1):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-ac', str(ch), '-ar', str(SR), '-f', 'f32le', '-'],
                         capture_output=True, check=True).stdout
    x = np.frombuffer(raw, dtype=np.float32)
    return x if ch == 1 else x.reshape(-1, ch)


# ---------------------------------------------------------------------------
# Alignment and pause trim
# ---------------------------------------------------------------------------
def align(vid):
    cfg = json.load(open(os.path.join(ROOT, 'videos', f'{vid}_script.json')))
    x = load(os.path.join(ROOT, cfg['clip']))
    regs, _ = speech_regions(x)
    texts = cfg['regions']
    assert len(regs) == len(texts), f'{len(regs)} regions vs {len(texts)} texts'

    from faster_whisper import WhisperModel
    from faster_whisper.tokenizer import Tokenizer
    from faster_whisper.audio import pad_or_trim
    model = WhisperModel('large-v3', device='cpu', compute_type='int8', cpu_threads=4)
    tok = Tokenizer(model.hf_tokenizer, True, task='transcribe', language='mn')
    x16 = signal.resample_poly(x, 1, 3).astype(np.float32)

    words = []
    for (a, b), text in zip(regs, texts):
        seg = x16[int(a * 16000):int(b * 16000)]
        feats = model.feature_extractor(seg)
        n = feats.shape[-1]
        enc = model.encode(pad_or_trim(feats))
        ids = tok.encode(' ' + text.strip())
        ali = model.find_alignment(tok, [ids], enc, n)[0]
        for w in ali:
            s = w['word'].strip()
            if not s:
                continue
            if words and all(ch in ',.?!:;…' for ch in s):
                words[-1][0] += s          # punctuation rides on the previous word
                continue
            words.append([s, round(a + float(w['start']), 3), round(a + float(w['end']), 3)])

    # first word of each region starts no earlier than the unpadded speech onset
    # build the trimmed timeline
    long_at = cfg.get('long_pause_before_region')
    keep, t_new = [], 0.0
    for i, (a, b) in enumerate(regs):
        if i:
            t_new += (LONG_PAUSE - 0.12) if i == long_at else PAUSE
        keep.append((a, b, t_new))
        t_new += b - a

    def remap(t):
        for a, b, n0 in keep:
            if t <= b + 1e-6:
                return n0 + max(0.0, t - a)
        a, b, n0 = keep[-1]
        return n0 + (b - a)

    out_words = [[w, round(remap(s), 3), round(remap(e), 3)] for w, s, e in words]

    # assemble trimmed voice with short fades at every join
    fade = int(0.008 * SR)
    total = int(np.ceil(t_new * SR)) + 1
    v = np.zeros(total, dtype=np.float32)
    for a, b, n0 in keep:
        seg = x[int(a * SR):int(b * SR)].copy()
        env = np.ones(len(seg), dtype=np.float32)
        env[:fade] = np.linspace(0, 1, fade)
        env[-fade:] = np.linspace(1, 0, fade)
        i0 = int(round(n0 * SR))
        v[i0:i0 + len(seg)] += (seg * env)[:max(0, total - i0)]

    bdir = os.path.join(ROOT, 'build', vid)
    os.makedirs(bdir, exist_ok=True)
    raw = os.path.join(bdir, 'voice_raw.wav')
    wav_write(raw, v)
    # Dialogue chain: highpass 75 Hz, gentle 3 kHz lift, ~3:1 compression.
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', raw, '-af',
                    'highpass=f=75:poles=2,afftdn=nf=-45:nr=6,equalizer=f=3000:t=q:w=0.9:g=2.5,'
                    'acompressor=threshold=-24dB:ratio=3:attack=6:release=140:knee=4:makeup=3',
                    '-ar', str(SR), '-ac', '1', '-c:a', 'pcm_f32le', os.path.join(bdir, 'voice.wav')], check=True)

    with open(os.path.join(ROOT, 'videos', f'{vid}_words.js'), 'w') as f:
        f.write('// Generated by audio.py align: [word, onset, end] on the trimmed voice timeline (s).\n')
        f.write(f'window.VOICE_END = {t_new:.3f};\n')
        f.write('window.WORDS = [\n' + ',\n'.join('  ' + json.dumps(w, ensure_ascii=False) for w in out_words) + '\n];\n')
    print(f'{vid}: {len(out_words)} words, voice {len(x)/SR:.2f} s -> {t_new:.2f} s')
    for w in out_words:
        print(f'  {w[1]:6.2f} {w[2]:6.2f}  {w[0]}')


# ---------------------------------------------------------------------------
# Bed: warm minimal piano + pad, 88 bpm, D major, never stops
# ---------------------------------------------------------------------------
def midi_hz(m):
    return 440.0 * 2 ** ((m - 69) / 12)


def piano(f, dur, vel, sr=SR):
    t = np.arange(int(dur * sr)) / sr
    y = np.zeros_like(t)
    for k in range(1, 8):
        amp = vel / k ** 1.6
        dec = 1.8 + 1.1 * k
        inh = f * k * (1 + 0.0004 * k * k)
        y += amp * np.sin(2 * np.pi * inh * t + 0.3 * k) * np.exp(-dec * t)
    att = np.minimum(1, t / 0.006)
    return (y * att).astype(np.float32)


def pad_voice(f, dur, sr=SR):
    t = np.arange(int(dur * sr)) / sr
    y = np.zeros_like(t)
    for det in (-0.12, 0.0, 0.11):
        ff = f * 2 ** (det / 12)
        for k in range(1, 6):
            y += np.sin(2 * np.pi * ff * k * t + det * 7 + k) / (k ** 2.2)
    env = np.minimum(1, t / 0.9) * np.minimum(1, (dur - t) / 1.0).clip(0, 1)
    return (y * env * 0.18).astype(np.float32)


def reverb(x, secs=2.2, seed=3):
    rng = np.random.default_rng(seed)
    n = int(secs * SR)
    ir = rng.standard_normal(n).astype(np.float32) * np.exp(-np.arange(n) / SR * 3.2).astype(np.float32)
    b, a = signal.butter(2, 5000 / (SR / 2))
    ir = signal.lfilter(b, a, ir).astype(np.float32)
    ir /= np.sqrt((ir ** 2).sum())
    return signal.fftconvolve(x, ir)[:len(x)].astype(np.float32)


def bed(total):
    bpm = 88.0
    beat = 60 / bpm
    bar = beat * 4
    chords = [  # Dmaj9, Bm7, Gmaj7, Asus4 -> A
        dict(root=38, pad=[62, 66, 69, 73], arp=[74, 78, 81, 76, 73, 78, 81, 76]),
        dict(root=35, pad=[59, 62, 66, 69], arp=[71, 74, 78, 74, 69, 74, 78, 74]),
        dict(root=31, pad=[59, 62, 66, 67], arp=[71, 74, 79, 74, 67, 74, 78, 74]),
        dict(root=33, pad=[57, 62, 64, 69], arp=[69, 74, 76, 73, 69, 73, 76, 73]),
    ]
    n = int((total + 3) * SR)
    L = np.zeros(n, np.float32)
    Rt = np.zeros(n, np.float32)
    rng = np.random.default_rng(7)
    nb = int(np.ceil(total / bar)) + 1
    for bi in range(nb):
        c = chords[bi % 4]
        t0 = bi * bar
        i0 = int(t0 * SR)
        if i0 >= n:
            break
        # pad, overlapping into the next bar for a seamless bed
        for m in c['pad']:
            p = pad_voice(midi_hz(m), bar + 1.2)
            j = min(n, i0 + len(p))
            L[i0:j] += p[:j - i0] * 0.8
            Rt[i0:j] += p[:j - i0] * 0.8
        # soft bass
        bs = piano(midi_hz(c['root']), bar, 0.55)
        j = min(n, i0 + len(bs)); L[i0:j] += bs[:j - i0]; Rt[i0:j] += bs[:j - i0]
        # eighth-note felt piano pulse
        for k, m in enumerate(c['arp']):
            ts = t0 + k * beat / 2 + rng.normal(0, 0.006)
            vel = (0.42 if k % 2 == 0 else 0.26) * rng.uniform(0.85, 1.05)
            p = piano(midi_hz(m), 1.6, vel)
            i = int(ts * SR); j = min(n, i + len(p))
            if i >= n:
                continue
            pan = 0.5 + 0.18 * np.sin(k * 1.3)
            L[i:j] += p[:j - i] * (1 - pan) * 1.2
            Rt[i:j] += p[:j - i] * pan * 1.2
    b, a = signal.butter(2, 4200 / (SR / 2))
    L = signal.lfilter(b, a, L).astype(np.float32)
    Rt = signal.lfilter(b, a, Rt).astype(np.float32)
    L = L * 0.75 + reverb(L, seed=3) * 0.45
    Rt = Rt * 0.75 + reverb(Rt, seed=4) * 0.45
    y = np.stack([L, Rt], 1)[:int(total * SR)]
    fi = int(0.05 * SR)
    y[:fi] *= np.linspace(0, 1, fi)[:, None]
    fo = int(0.6 * SR)
    y[-fo:] *= np.linspace(1, 0, fo)[:, None] ** 1.5
    return y


# ---------------------------------------------------------------------------
# Effects
# ---------------------------------------------------------------------------
def env_ad(n, a, d_rate):
    t = np.arange(n) / SR
    return (np.minimum(1, t / a) * np.exp(-d_rate * t)).astype(np.float32)


def sfx_sub():
    n = int(0.8 * SR); t = np.arange(n) / SR
    f = 45 * (38 / 45) ** (t / 0.8)
    ph = 2 * np.pi * np.cumsum(f) / SR
    y = np.sin(ph) + 0.35 * np.sin(2 * ph) + 0.12 * np.sin(3 * ph)   # harmonics keep it audible on phones
    y *= np.minimum(1, t / 0.004) * np.exp(-3.4 * t) * np.minimum(1, (0.8 - t) / 0.08)
    click = np.random.default_rng(1).standard_normal(n) * np.exp(-t * 400) * 0.25
    b, a = signal.butter(2, 900 / (SR / 2))
    y = y + signal.lfilter(b, a, click)
    return np.stack([y, y], 1).astype(np.float32)


def sfx_noise_sweep(dur, f0, f1, q, shape, pan=None, seed=2):
    n = int(dur * SR); t = np.arange(n) / SR
    x = np.random.default_rng(seed).standard_normal(n).astype(np.float32)
    out = np.zeros(n, np.float32)
    blk = 256
    zi = None
    for i in range(0, n, blk):
        k = i / n
        fc = f0 * (f1 / f0) ** k
        b, a = signal.iirpeak(fc / (SR / 2), q)
        if zi is None:
            zi = signal.lfilter_zi(b, a) * 0
        out[i:i + blk], zi = signal.lfilter(b, a, x[i:i + blk], zi=zi)
    env = shape(t / dur)
    y = out * env
    if pan is None:
        return np.stack([y, y], 1)
    p = pan(t / dur)
    return np.stack([y * np.cos(p * np.pi / 2), y * np.sin(p * np.pi / 2)], 1).astype(np.float32)


def sfx_swish():   # silk, 0.6 s, travels left to right with the ribbon
    return sfx_noise_sweep(0.6, 700, 3600, 1.4, lambda k: np.sin(np.pi * np.clip(k, 0, 1) ** 0.8) ** 1.6,
                           pan=lambda k: 0.15 + 0.7 * k)


def sfx_whoosh():  # airy, 0.42 s
    return sfx_noise_sweep(0.42, 1800, 5200, 0.9, lambda k: np.sin(np.pi * k) ** 2, seed=5) * 0.7


def sfx_tick():    # wooden, near 1.2 kHz
    n = int(0.12 * SR); t = np.arange(n) / SR
    y = np.sin(2 * np.pi * 1200 * t) * np.exp(-t * 70) + 0.45 * np.sin(2 * np.pi * 2650 * t) * np.exp(-t * 140)
    y += np.random.default_rng(4).standard_normal(n) * np.exp(-t * 900) * 0.3
    y *= np.minimum(1, t / 0.0008)
    return np.stack([y, y], 1).astype(np.float32) * 0.6


def sfx_thud():
    n = int(0.35 * SR); t = np.arange(n) / SR
    y = np.sin(2 * np.pi * 70 * t * (1 - 0.3 * t)) * np.exp(-t * 14) + 0.3 * np.sin(2 * np.pi * 140 * t) * np.exp(-t * 20)
    return np.stack([y, y], 1).astype(np.float32)


SFX = dict(sub=sfx_sub, swish=sfx_swish, whoosh=sfx_whoosh, tick=sfx_tick, thud=sfx_thud)


def mix(vid):
    bdir = os.path.join(ROOT, 'build', vid)
    cues = json.load(open(os.path.join(bdir, 'cues.json')))
    total = cues['end']
    meter = pyln.Meter(SR)

    v = wav_read(os.path.join(bdir, 'voice.wav'))
    v = v / (10 ** ((meter.integrated_loudness(v) - (-16)) / 20))          # dialogue at 0 dB reference (-16 LUFS)
    voice = np.zeros((int(total * SR), 2), np.float32)
    m = min(len(v), len(voice)); voice[:m, 0] = v[:m]; voice[:m, 1] = v[:m]

    b = bed(total)
    b = b / (10 ** ((meter.integrated_loudness(b) - (-30)) / 20))          # bed 14 dB under dialogue
    # duck the bed 3 dB for 0.4 s before hits
    g = np.ones(len(b), np.float32)
    for c in cues['cues']:
        if c['type'] in ('sub', 'thud'):
            i1 = int(c['t'] * SR); i0 = max(0, i1 - int(0.4 * SR)); i2 = min(len(g), i1 + int(0.5 * SR))
            g[i0:i1] = np.minimum(g[i0:i1], np.linspace(1, 0.708, i1 - i0))
            g[i1:i2] = np.minimum(g[i1:i2], np.linspace(0.708, 1, i2 - i1))
    b *= g[:, None]

    fx = np.zeros_like(voice)
    for c in cues['cues']:
        s = SFX[c['type']]() * c.get('gain', 1.0)
        i = int(max(0, c['t']) * SR); j = min(len(fx), i + len(s))
        fx[i:j] += s[:j - i]
    if np.abs(fx).max() > 0:
        # effects 8 dB under dialogue, measured on the active parts
        act = fx[np.abs(fx).max(1) > 1e-4]
        lf = meter.integrated_loudness(act) if len(act) > SR * 0.4 else -30
        fx = fx / (10 ** ((lf - (-24)) / 20))

    y = voice + b[:len(voice)] + fx
    pre = os.path.join(bdir, 'mix_pre.wav')
    wav_write(pre, y)
    # two-pass loudnorm to -14 LUFS, true peak -1.0 dBTP
    r = subprocess.run(['ffmpeg', '-hide_banner', '-i', pre, '-af', 'loudnorm=I=-14:TP=-1.5:LRA=4:print_format=json', '-f', 'null', '-'],
                       capture_output=True, text=True).stderr
    js = json.loads(r[r.rindex('{'):r.rindex('}') + 1])
    af = (f"loudnorm=I=-14:TP=-1.5:LRA=4:measured_I={js['input_i']}:measured_TP={js['input_tp']}:"
          f"measured_LRA={js['input_lra']}:measured_thresh={js['input_thresh']}:offset={js['target_offset']}:linear=true,"
          f"alimiter=limit=0.84:level=false:attack=3:release=60")
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', pre, '-af', af, '-ar', str(SR), '-c:a', 'pcm_f32le',
                    os.path.join(bdir, 'mix.wav')], check=True)
    r = subprocess.run(['ffmpeg', '-hide_banner', '-nostats', '-i', os.path.join(bdir, 'mix.wav'), '-af', 'ebur128=peak=true', '-f', 'null', '-'],
                       capture_output=True, text=True).stderr
    summ = r[r.rindex('Summary:'):]
    print(vid, ' '.join(l.strip() for l in summ.splitlines() if any(k in l for k in ('I:', 'LRA:', 'Peak:'))))


if __name__ == '__main__':
    cmd, vid = sys.argv[1], sys.argv[2]
    {'align': align, 'mix': mix}[cmd](vid)
